#!/usr/bin/env node
/**
 * update-manifest.mjs - is `release/latest.yml` telling the truth about the
 * artifacts sitting next to it, and if signing changed them, make it true again.
 *
 * WHY THIS EXISTS. `electron-updater` downloads the installer named in
 * `latest.yml` and rejects it unless the sha512 and size in that manifest match
 * the bytes it got. A manifest that describes different bytes breaks auto-update
 * for everyone already on the previous version, and breaks it SILENTLY - nothing
 * in a build log goes red. This repo has already shipped that failure once: an
 * earlier `package-signed.ps1` packed first and ran `Set-AuthenticodeSignature`
 * afterwards, so every installer gained ~7 KB of Authenticode data *after*
 * electron-builder had written the manifest.
 *
 * `scripts/package-signed.ps1` guards the local path with an inline PowerShell
 * verification block. This is the same guard for a path where PowerShell is not
 * the tool of choice (CI), plus the repair the local path never needed:
 *
 *   --check     (default) hash every artifact and compare against the manifest.
 *               Nothing is written. This is a gate, and it must run last, after
 *               anything that could touch the installer.
 *
 *   --rewrite   the installer was re-signed AFTER electron-builder wrote the
 *               manifest (which is what a signing service such as SignPath does
 *               - it takes the finished installer and hands back a different
 *               file). Regenerate the blockmap, write the new sha512/size into
 *               latest.yml, then run --check.
 *
 * --rewrite has NEVER RUN against a real signing service, because no
 * distribution certificate has been granted yet. Its arithmetic is unit-tested
 * (`tests/updateManifest.test.ts`); its integration is not.
 *
 * Usage:
 *   node scripts/update-manifest.mjs            # check
 *   node scripts/update-manifest.mjs --rewrite  # repair, then check
 *   node scripts/update-manifest.mjs --dir some/other/release
 *
 * Exit: 0 = consistent - 1 = a check failed - 2 = usage error.
 */
import { createHash } from "node:crypto"
import { existsSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

/* ------------------------------------------------------------------ parsing */

// latest.yml is generated by electron-builder and is three keys deep at most,
// so it is parsed line by line rather than by pulling in a YAML library. The
// shape is asserted, not assumed: anything unexpected throws instead of being
// silently half-understood. `js-yaml` is only ever a transitive dependency of
// electron-builder here, and a build script that breaks when a devDependency
// re-arranges its own tree is worse than twenty lines of parsing.

const KV = /^([A-Za-z0-9_]+):\s*(.*)$/

function unquote(v) {
    const s = v.trim()
    if (s.length >= 2 && ((s[0] === "'" && s.endsWith("'")) || (s[0] === '"' && s.endsWith('"')))) {
        return s.slice(1, -1)
    }
    return s
}

/** The entries of the manifest's `files:` list, in order. */
export function manifestFiles(text) {
    const out = []
    let inFiles = false
    let cur = null
    for (const line of text.split(/\r?\n/)) {
        if (/^files:\s*$/.test(line)) {
            inFiles = true
            continue
        }
        if (!inFiles) continue
        if (line.trim() === "") continue
        // A non-indented line means the `files:` block is over.
        if (/^\S/.test(line)) break
        const dash = /^\s*-\s*(.*)$/.exec(line)
        if (dash) {
            cur = {}
            out.push(cur)
            const kv = KV.exec(dash[1].trim())
            if (kv) cur[kv[1]] = unquote(kv[2])
            continue
        }
        const kv = KV.exec(line.trim())
        if (kv && cur != null) cur[kv[1]] = unquote(kv[2])
    }
    return out.map(e => ({
        url: e.url,
        sha512: e.sha512,
        size: e.size == null ? null : Number(e.size),
        blockMapSize: e.blockMapSize == null ? null : Number(e.blockMapSize)
    }))
}

/** The manifest's top-level `path:` - the file electron-updater will fetch. */
export function manifestPath(text) {
    const m = /^path:\s*(.+)$/m.exec(text)
    return m == null ? null : unquote(m[1])
}

/** The manifest's top-level `sha512:` (a duplicate of the single file entry's). */
export function manifestSha512(text) {
    const m = /^sha512:\s*(.+)$/m.exec(text)
    return m == null ? null : unquote(m[1])
}

/**
 * Write a new sha512/size for `url` into the manifest text.
 *
 * The value appears twice - once under `files:` and once at the top level - and
 * electron-updater reads the top-level pair. Both are replaced, which is why
 * this refuses a manifest carrying more than one file entry: with two artifacts
 * the top-level pair belongs to only one of them and a blind replacement would
 * corrupt the other.
 */
export function patchManifest(text, next) {
    const entries = manifestFiles(text)
    if (entries.length !== 1) {
        throw new Error(`expected exactly 1 entry under files:, found ${entries.length} - refusing to guess which one the top-level sha512 belongs to`)
    }
    const cur = entries[0]
    if (cur.url !== next.url) {
        throw new Error(`manifest names '${cur.url}' but the artifact is '${next.url}'`)
    }
    if (cur.blockMapSize != null) {
        // nsis-web and AppImage embed the blockmap in the artifact and record its
        // length here. Re-signing changes that length, and recomputing it means
        // re-appending the blockmap, not editing a number.
        throw new Error("manifest carries blockMapSize (an embedded blockmap); this script cannot refresh that - re-run electron-builder instead")
    }
    if (cur.sha512 == null || cur.size == null) {
        throw new Error("manifest entry is missing sha512 or size")
    }
    if (manifestPath(text) !== next.url) {
        throw new Error(`manifest's top-level path is '${manifestPath(text)}', not '${next.url}'`)
    }

    const eol = text.includes("\r\n") ? "\r\n" : "\n"
    const sizeLine = new RegExp(`^\\s*size:\\s*${cur.size}\\s*$`)
    let out = text.split(cur.sha512).join(next.sha512)
    out = out
        .split(/\r?\n/)
        .map(line => (sizeLine.test(line) ? line.replace(/size:\s*\d+\s*$/, `size: ${next.size}`) : line))
        .join(eol)

    const after = manifestFiles(out)
    if (after[0].sha512 !== next.sha512 || after[0].size !== next.size || manifestSha512(out) !== next.sha512) {
        throw new Error("manifest rewrite did not take effect - refusing to write a half-patched manifest")
    }
    return out
}

/* ----------------------------------------------------------------- the disk */

const sha512Of = file => createHash("sha512").update(readFileSync(file)).digest("base64")

/** The four artifacts a release must carry, derived the way electron-builder names them. */
export function artifactNames(pkg) {
    const product = pkg?.build?.productName ?? pkg?.productName ?? pkg?.name ?? "app"
    const version = pkg?.version
    return {
        installer: `${product}-Setup-${version}.exe`,
        blockmap: `${product}-Setup-${version}.exe.blockmap`,
        portable: `${product}-Portable-${version}.exe`,
        manifest: "latest.yml"
    }
}

async function rewrite(dir, names) {
    let buildBlockMap
    try {
        ;({ buildBlockMap } = await import("app-builder-lib/out/targets/blockmap/blockmap.js"))
    } catch (e) {
        // Deliberately fatal. The alternative - carry on with the blockmap
        // electron-builder made for the *unsigned* installer - ships a manifest
        // whose differential-download data describes bytes nobody has.
        throw new Error(
            "could not load electron-builder's blockmap builder " +
                "(app-builder-lib/out/targets/blockmap/blockmap.js): " +
                e.message +
                "\nThe path moved in a devDependency bump. Find it again; do not skip this step."
        )
    }
    if (typeof buildBlockMap !== "function") {
        throw new Error("app-builder-lib no longer exports buildBlockMap from that path")
    }

    const installer = join(dir, names.installer)
    console.log(`==> rebuilding ${names.blockmap} for the re-signed installer`)
    // "gzip" and the sibling .blockmap file name are what electron-builder's own
    // createBlockmap() passes for an nsis target (app-builder-lib
    // out/targets/differentialUpdateInfoBuilder.js). Same call, same output.
    const info = await buildBlockMap(installer, "gzip", `${installer}.blockmap`)
    console.log(`    sha512 ${info.sha512}`)
    console.log(`    size   ${info.size}`)

    const manifest = join(dir, names.manifest)
    const patched = patchManifest(readFileSync(manifest, "utf8"), {
        url: names.installer,
        sha512: info.sha512,
        size: info.size
    })
    writeFileSync(manifest, patched)
    console.log(`==> wrote ${names.manifest}`)
}

function check(dir, names) {
    const failed = []
    const say = (label, ok, detail) => console.log(`  ${ok ? "ok  " : "FAIL"} ${label}${detail ? " - " + detail : ""}`)

    for (const f of [names.installer, names.portable, names.blockmap, names.manifest]) {
        const p = join(dir, f)
        if (!existsSync(p)) {
            say(f, false, "missing")
            failed.push(`missing artifact: ${f}`)
            continue
        }
        const size = statSync(p).size
        if (size === 0) {
            say(f, false, "zero bytes")
            failed.push(`zero-byte artifact: ${f}`)
            continue
        }
        say(f, true, `${(size / 1048576).toFixed(1)} MB`)
    }
    if (failed.length > 0) return failed

    const text = readFileSync(join(dir, names.manifest), "utf8")
    const entries = manifestFiles(text)

    if (entries.length !== 1) {
        failed.push(`latest.yml lists ${entries.length} files, expected 1`)
        return failed
    }
    const entry = entries[0]

    // GitHub rewrites spaces in release-asset names, so a manifest naming a file
    // that is not the one uploaded 404s the updater rather than failing a hash.
    const pathOk = manifestPath(text) === names.installer
    say("latest.yml path names the installer", pathOk, pathOk ? "" : `path: ${manifestPath(text)}`)
    if (!pathOk) failed.push(`latest.yml path is '${manifestPath(text)}', not '${names.installer}'`)

    const urlOk = entry.url === names.installer
    say("latest.yml files[0].url names the installer", urlOk, urlOk ? "" : `url: ${entry.url}`)
    if (!urlOk) failed.push(`latest.yml files[0].url is '${entry.url}', not '${names.installer}'`)

    const dupOk = manifestSha512(text) === entry.sha512
    say("top-level sha512 agrees with files[0]", dupOk)
    if (!dupOk) failed.push("latest.yml top-level sha512 disagrees with its own files[0] entry")

    const installer = join(dir, names.installer)
    const realSha = sha512Of(installer)
    const realSize = statSync(installer).size

    const shaOk = realSha === entry.sha512
    say("sha512 matches the installer on disk", shaOk, shaOk ? "" : `disk ${realSha} / manifest ${entry.sha512}`)
    if (!shaOk) failed.push("latest.yml sha512 does not match the installer - electron-updater would reject the download")

    const sizeOk = realSize === entry.size
    say("size matches the installer on disk", sizeOk, sizeOk ? "" : `disk ${realSize} / manifest ${entry.size}`)
    if (!sizeOk) failed.push(`latest.yml size is ${entry.size}, installer is ${realSize}`)

    return failed
}

export async function main(argv) {
    if (argv.includes("--help") || argv.includes("-h")) {
        console.log("usage: node scripts/update-manifest.mjs [--check|--rewrite] [--dir <release dir>]")
        return 2
    }
    const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
    const dirArg = argv.indexOf("--dir")
    const dir = dirArg === -1 ? join(root, "release") : resolve(argv[dirArg + 1] ?? "")
    const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"))
    const names = artifactNames(pkg)

    console.log(`==> ${pkg.version} in ${dir}`)
    if (!existsSync(join(dir, names.manifest))) {
        console.error(`no ${names.manifest} in ${dir} - electron-builder writes it only when a publish provider is configured (package.json build.publish)`)
        return 1
    }

    if (argv.includes("--rewrite")) {
        await rewrite(dir, names)
    }

    console.log("==> checking the manifest against the artifacts")
    const failed = check(dir, names)
    if (failed.length > 0) {
        console.error("")
        console.error("RELEASE IS NOT PUBLISHABLE:")
        for (const f of failed) console.error(`  - ${f}`)
        return 1
    }
    console.log("")
    console.log("latest.yml describes the artifacts on disk. Auto-update will accept this release.")
    return 0
}

if (resolve(process.argv[1] || "") === resolve(fileURLToPath(import.meta.url))) {
    process.exit(await main(process.argv.slice(2)))
}
